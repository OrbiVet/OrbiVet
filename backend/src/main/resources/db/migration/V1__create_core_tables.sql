-- KAN-69: tabelas base da funcionalidade core (gestão de tutores e animais).
-- Convenções: nomes em snake_case, ids BIGINT identity (GenerationType.IDENTITY),
-- valores de domínio em MAIÚSCULAS para mapear com @Enumerated(EnumType.STRING).

-- ---------------------------------------------------------------------------
-- usuario: conta de acesso (login). Colunas mapeadas pela entidade Usuario
-- (KAN-71/KAN-72) precisam bater exatamente, pois ddl-auto=validate.
-- ---------------------------------------------------------------------------
CREATE TABLE usuario (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                   VARCHAR(150) NOT NULL,
    email                  VARCHAR(150) NOT NULL,
    senha_hash             VARCHAR(255) NOT NULL,
    criado_em              TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    exclusao_solicitada_em TIMESTAMP,

    -- Ainda não mapeadas na entidade; já previstas na tela "Criar conta"
    perfil                 VARCHAR(20)  NOT NULL DEFAULT 'TUTOR',
    telefone               VARCHAR(20),

    CONSTRAINT uk_usuario_email UNIQUE (email),
    CONSTRAINT ck_usuario_perfil CHECK (perfil IN ('TUTOR', 'PROFISSIONAL', 'EMPRESA', 'ONG'))
);

-- ---------------------------------------------------------------------------
-- tutor: dados de quem é responsável pelos animais ("Dono" na modelagem).
-- Nome, e-mail e telefone ficam em usuario, para não duplicar informação.
-- ---------------------------------------------------------------------------
CREATE TABLE tutor (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT       NOT NULL,
    cpf        VARCHAR(11),
    endereco   VARCHAR(255),
    criado_em  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_tutor_usuario UNIQUE (usuario_id),
    CONSTRAINT uk_tutor_cpf UNIQUE (cpf),
    CONSTRAINT ck_tutor_cpf CHECK (cpf ~ '^[0-9]{11}$'),
    CONSTRAINT fk_tutor_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id)
);

-- ---------------------------------------------------------------------------
-- animal: pet de um tutor.
-- ---------------------------------------------------------------------------
CREATE TABLE animal (
    id                            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tutor_id                      BIGINT        NOT NULL,
    nome                          VARCHAR(60)   NOT NULL,
    especie                       VARCHAR(20)   NOT NULL,
    sexo                          VARCHAR(10)   NOT NULL,
    raca                          VARCHAR(80),
    -- A tela pede só mês/ano: gravar o dia 1 do mês informado
    data_nascimento               DATE,
    peso                          NUMERIC(6, 2),
    cor_coleira                   VARCHAR(20)   NOT NULL,
    -- URL do arquivo no armazenamento de objetos (a foto não fica no banco)
    foto_url                      VARCHAR(500),
    caracteristicas_fisicas       TEXT,
    alergias                      TEXT,
    valor_nutricional_alimentacao TEXT,
    observacoes                   TEXT,
    criado_em                     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_animal_tutor FOREIGN KEY (tutor_id) REFERENCES tutor (id),
    CONSTRAINT ck_animal_especie CHECK (especie IN ('CAO', 'GATO', 'OUTRO')),
    CONSTRAINT ck_animal_sexo CHECK (sexo IN ('MACHO', 'FEMEA')),
    CONSTRAINT ck_animal_cor_coleira CHECK (cor_coleira IN ('LARANJA', 'COBALTO', 'MOSTARDA', 'MAGENTA', 'TURQUESA')),
    CONSTRAINT ck_animal_peso CHECK (peso IS NULL OR peso > 0)
);

CREATE INDEX idx_animal_tutor ON animal (tutor_id);
